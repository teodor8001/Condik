create policy "project members can view site photos"
on storage.objects for select to authenticated
using (
    bucket_id = 'santier-fotografii'
    and (storage.foldername(name))[1] ~ '^[0-9]+$'
    and (select private.can_access_project(((storage.foldername(name))[1])::bigint))
    and (select private.has_permission('site.view'))
);
create policy "project members can upload site photos"
on storage.objects for insert to authenticated
with check (
    bucket_id = 'santier-fotografii'
    and (storage.foldername(name))[1] ~ '^[0-9]+$'
    and (select private.can_access_project(((storage.foldername(name))[1])::bigint))
    and (select private.has_permission('site.view'))
    and owner_id = (select auth.uid()::text)
);
create policy "photo owners and site managers can delete site photos"
on storage.objects for delete to authenticated
using (
    bucket_id = 'santier-fotografii'
    and (storage.foldername(name))[1] ~ '^[0-9]+$'
    and (select private.can_access_project(((storage.foldername(name))[1])::bigint))
    and (owner_id = (select auth.uid()::text) or (select private.has_permission('site.manage')))
);

