create policy "project members can read attendance"
on public.prezente_santier for select to authenticated
using ((select private.can_access_project(id_proiect)) and (select private.has_permission('site.view')));
create policy "site managers can create attendance"
on public.prezente_santier for insert to authenticated
with check (
    (select private.can_access_project(id_proiect))
    and (select private.has_permission('site.manage'))
    and (select private.same_company_user(id_utilizator))
    and inregistrat_de = (select private.current_user_id())
);
create policy "site managers can update attendance"
on public.prezente_santier for update to authenticated
using ((select private.can_access_project(id_proiect)) and (select private.has_permission('site.manage')))
with check (
    (select private.can_access_project(id_proiect))
    and (select private.same_company_user(id_utilizator))
    and inregistrat_de = (select private.current_user_id())
);
create policy "site managers can delete attendance"
on public.prezente_santier for delete to authenticated
using ((select private.can_access_project(id_proiect)) and (select private.has_permission('site.manage')));

