create table public.prezente_santier (
    id_prezenta bigint generated by default as identity primary key,
    id_proiect bigint not null references public.proiecte(id_proiect) on delete cascade,
    id_utilizator bigint not null references public.utilizatori(id_utilizator) on delete cascade,
    data date not null default current_date,
    status text not null default 'prezent' check (status in ('prezent', 'absent', 'concediu', 'medical')),
    ora_intrare time,
    ora_iesire time,
    observatii text,
    inregistrat_de bigint not null references public.utilizatori(id_utilizator),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (id_proiect, id_utilizator, data),
    check (ora_iesire is null or ora_intrare is null or ora_iesire >= ora_intrare)
);

create table public.corecturi_santier (
    id_corectura bigint generated by default as identity primary key,
    id_proiect bigint not null references public.proiecte(id_proiect) on delete cascade,
    id_zona bigint references public.zone(id_zona) on delete set null,
    titlu text not null check (length(trim(titlu)) between 1 and 160),
    descriere text not null check (length(trim(descriere)) between 1 and 4000),
    severitate text not null default 'medie' check (severitate in ('scazuta', 'medie', 'ridicata', 'critica')),
    status text not null default 'deschisa' check (status in ('deschisa', 'in_lucru', 'rezolvata', 'respinsa')),
    atribuit_catre bigint references public.utilizatori(id_utilizator) on delete set null,
    creat_de bigint not null references public.utilizatori(id_utilizator),
    termen date,
    rezolvat_la timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.jurnal_santier (
    id_intrare bigint generated by default as identity primary key,
    id_proiect bigint not null references public.proiecte(id_proiect) on delete cascade,
    data date not null default current_date,
    tip text not null check (tip in ('observatie', 'fotografie', 'incident')),
    titlu text not null check (length(trim(titlu)) between 1 and 160),
    descriere text not null check (length(trim(descriere)) between 1 and 4000),
    severitate text check (severitate is null or severitate in ('scazuta', 'medie', 'ridicata', 'critica')),
    cale_fotografie text,
    creat_de bigint not null references public.utilizatori(id_utilizator),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (tip <> 'fotografie' or cale_fotografie is not null)
);

create table public.inchideri_santier (
    id_inchidere bigint generated by default as identity primary key,
    id_proiect bigint not null references public.proiecte(id_proiect) on delete cascade,
    data date not null default current_date,
    rezumat text not null check (length(trim(rezumat)) between 1 and 6000),
    blocaje text,
    plan_urmatoarea_zi text,
    inchis_de bigint not null references public.utilizatori(id_utilizator),
    inchis_la timestamptz not null default now(),
    redeschis_la timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (id_proiect, data)
);

create index prezente_santier_project_date_idx
    on public.prezente_santier (id_proiect, data desc);
create index prezente_santier_user_date_idx
    on public.prezente_santier (id_utilizator, data desc);
create index corecturi_santier_project_status_idx
    on public.corecturi_santier (id_proiect, status, created_at desc);
create index corecturi_santier_assignee_open_idx
    on public.corecturi_santier (atribuit_catre, status)
    where atribuit_catre is not null and status in ('deschisa', 'in_lucru');
create index jurnal_santier_project_date_idx
    on public.jurnal_santier (id_proiect, data desc, created_at desc);
create index inchideri_santier_project_date_idx
    on public.inchideri_santier (id_proiect, data desc);

create or replace function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end
$$;

revoke all on function private.touch_updated_at() from public, anon, authenticated;

create trigger prezente_santier_touch_updated_at
before update on public.prezente_santier
for each row execute function private.touch_updated_at();
create trigger corecturi_santier_touch_updated_at
before update on public.corecturi_santier
for each row execute function private.touch_updated_at();
create trigger jurnal_santier_touch_updated_at
before update on public.jurnal_santier
for each row execute function private.touch_updated_at();
create trigger inchideri_santier_touch_updated_at
before update on public.inchideri_santier
for each row execute function private.touch_updated_at();

